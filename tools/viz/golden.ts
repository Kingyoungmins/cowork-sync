/** This module is the process entry (tsx tools/viz/golden.ts, or node --import tsx), not an import. */
function isMain(url: string): boolean {
  const arg = process.argv[1];
  if (arg === undefined) return false;
  const canon = (p: string): string => {
    let r = resolve(p);
    try {
      r = realpathSync.native(r);
    } catch {
      // not a file on disk: compare as given
    }
    return process.platform === 'win32' ? r.toLowerCase() : r;
  };
  return canon(arg) === canon(fileURLToPath(url));
}

if (isMain(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
  runGolden(process.argv.slice(2), { root, io: { out: (l) => process.stdout.write(`${l}\n`), err: (l) => process.stderr.write(`${l}\n`) } }).then(
    (code) => {
      process.exitCode = code;
    },
    (e: unknown) => {
      process.stderr.write(`viz:golden: ${e instanceof Error ? (e.stack ?? e.message) : String(e)}\n`);
      process.exitCode = 1;
    },
  );
}
