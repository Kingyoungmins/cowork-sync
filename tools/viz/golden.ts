const USAGE = 'usage: npm run viz:golden [-- --update]';
const BOM = '\u{FEFF}';

/** The 1-based number of the first line where `a` and `b` differ (a missing file differs at line 1). */
function firstDifferingLine(a: string, b: string): number {
  const x = a.split('\n');
  const y = b.split('\n');
  let i = 0;
  while (i < x.length && i < y.length && x[i] === y[i]) i++;
  return i + 1;
}

function readOrNull(file: string): Buffer | null {
  try {
    return readFileSync(file);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw e;
  }
}

/**
 * argv: [] compares, ['--update'] writes; anything else is a usage error (2). Every set's files are generated first (a set that
 * throws fails the run), then taken in path order: compare mode exits 1 naming the first file that is missing or differs (with
 * its first differing line) and writes nothing; --update writes exactly the files that are missing or differ and exits 0.
 * A generated text with a CR or a BOM, or two sets naming one path, is a bug in the generator: it throws.
 */
export async function runGolden(argv: readonly string[], o: { root: string; sets?: readonly GoldenSet[]; io: GoldenIo }): Promise<number> {
  const update = argv.length === 1 && argv[0] === '--update';
  if (argv.length > 0 && !update) {
    o.io.err(USAGE);
    return 2;
  }
  const files: GoldenFile[] = [];
  for (const set of o.sets ?? GOLDEN_SETS) files.push(...(await set.files(o.root)));
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  for (let i = 0; i < files.length; i++) {
    const f = files[i]!;
    if (f.text.includes('\r') || f.text.startsWith(BOM)) throw new Error(`viz:golden: generated ${f.path} has a CR or a BOM`);
    if (i > 0 && files[i - 1]!.path === f.path) throw new Error(`viz:golden: two sets generate ${f.path}`);
  }
  const differing: Array<{ file: GoldenFile; old: Buffer | null }> = [];
  for (const file of files) {
    const old = readOrNull(join(o.root, ...file.path.split('/')));
    if (old === null || !old.equals(Buffer.from(file.text, 'utf8'))) differing.push({ file, old });
  }
  if (!update) {
    if (differing.length === 0) {
      o.io.out(`viz:golden: ${files.length} golden files match`);
      return 0;
    }
    const { file, old } = differing[0]!;
    const what = old === null ? 'is missing' : `differs at line ${firstDifferingLine(old.toString('utf8'), file.text)}`;
    o.io.err(`viz:golden: ${file.path} ${what} (${differing.length} of ${files.length} golden files differ)`);
    o.io.err('viz:golden: run `npm run viz:golden -- --update` and review the diff');
    return 1;
  }
  for (const { file } of differing) {
    const abs = join(o.root, ...file.path.split('/'));
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, Buffer.from(file.text, 'utf8'));
    o.io.out(`viz:golden: wrote ${file.path}`);
  }
  o.io.out(`viz:golden: ${differing.length} written, ${files.length - differing.length} unchanged`);
  return 0;
}

// ---- timelines of a room, for the board goldens and the export-demo tests ---------------------------------------------------

/** One serialized timeline of a whole board from height 0 (12 §3.3.5 "Serialization") and what its frames counted. */
export interface RoomTimeline { text: string; heights: number; unknown: number; malformed: number; shapeNull: number; }

/**
 * The room's whole board from height 0 through the timeline builder (TimelineBuilder.open + push per frame, which is what
 * buildTimeline does over an array; frames are streamed so no fold state outlives its frame), serialized by serializeTimeline.
 * unknown sums the builder's per-frame counts; malformed and shapeNull count R-V19's frames (only these make a git timeline's
 * unknown count exceed its exported demo's).
 */
export async function roomTimeline(src: RoomSource): Promise<RoomTimeline> {
  const tip = await src.tip();
  if (tip === null) throw new Error('roomTimeline: the room has no board');
  const start = await src.startAt(0);
  const b = TimelineBuilder.open(0, start);
  let unknown = 0;
  let malformed = 0;
  let shapeNull = 0;
  for await (const f of src.frames(start, 0, tip.height, ZERO_PEER)) {
    unknown += b.push(f).unknown;
    if (f.malformed) malformed++;
    if (f.height > 0 && f.code.changed && f.code.shape === null) shapeNull++;
  }
  return { text: serializeTimeline(b.timeline()), heights: tip.height + 1, unknown, malformed, shapeNull };
}

/** A step of a board script: a ScriptCommit (consecutive ones are written by one commitMany), a join, or an R-V19 fixture. */
type BoardStep = ScriptCommit | { join: string; o?: Parameters<BoardWriter['join']>[1] } | { malformed: Parameters<BoardWriter['malformed']>[0] };

