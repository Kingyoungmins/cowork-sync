/** One golden: its repository-relative, '/'-separated path and its exact text. */
export interface GoldenFile { path: string; text: string; }
/** A family of goldens generated together (files sorted or not: runGolden orders them by path). */
export interface GoldenSet { name: string; files(root: string): Promise<GoldenFile[]>; }
export interface GoldenIo { out(line: string): void; err(line: string): void; }

