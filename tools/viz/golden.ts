/** Writes golden board n into a fresh clone (one commitMany per run of ScriptCommits). The caller cleans the fixture up. */
export async function writeGoldenBoard(n: 1 | 2 | 3): Promise<{ fx: RepoFixture; w: BoardWriter }> {
  const spec = GOLDEN_BOARDS.find((b) => b.n === n)!;
  const fx = await makeRepoFixture(`viz-golden-board-${n}`);
  try {
    if (spec.branch !== 'main') await fx.repo.run(['update-ref', `refs/heads/${spec.branch}`, (await fx.repo.run(['rev-parse', '--verify', 'refs/heads/main'])).stdout.toString('utf8').trim()]);
    const w = await BoardWriter.create({ runner: fx.runner, paths: fx.paths, branch: spec.branch, seed: spec.seed });
    await w.genesis('ann');
    let batch: ScriptCommit[] = [];
    const flush = async (): Promise<void> => {
      if (batch.length > 0) await w.commitMany(batch);
      batch = [];
    };
    // Once a board commit names a tag as its live commit, fast-import cannot update the ref past it (git walks the board's
    // ancestry for the update and refuses the tag), so every later commit is written on its own.
    let tagged = false;
    for (const s of spec.steps()) {
      if ('join' in s) {
        await flush();
        await w.join(s.join, s.o);
      } else if ('malformed' in s) {
        await flush();
        await w.malformed(s.malformed);
        tagged ||= s.malformed === 'live_not_commit';
      } else if (tagged) {
        await w.commit(s);
      } else {
        batch.push(s);
      }
    }
    await flush();
    return { fx, w };
  } catch (e) {
    await fx.cleanup();
    throw e;
  }
}

/** Golden board n read twice: through the git source, and through its exported demo log and the demo source (VizGit only). */
export async function goldenBoardTimelines(n: 1 | 2 | 3): Promise<{ git: RoomTimeline; demo: RoomTimeline; demoBytes: Buffer }> {
  const { fx, w } = await writeGoldenBoard(n);
  try {
    const dataDir = join(fx.root, 'viz data');
    const runner = vizRunner(dataDir);
    const git = createVizGit({ runner, gitDir: fx.paths.gitDir, dataDir });
    const spec = GOLDEN_BOARDS.find((b) => b.n === n)!;
    const demoBytes = await exportDemo({ gitDir: fx.paths.gitDir, ref: w.ref, room: { room: 'a', name: `golden-${n}`, branch: spec.branch }, captions: [] }, { git });
    const log = parseDemoLog(demoBytes, new Set(DEMO_CAPTION_CODES));
    if ('line' in log) throw new Error(`golden board ${n}: the exported demo refuses at line ${log.line}`);
    const demo = await roomTimeline(new DemoRoomSource(log.rooms[0]!, log.commits.get('a')!));
    const roomSpec = { id: 'r00000000', kind: 'git' as const, label: `golden-${n}`, branch: spec.branch, gitDir: fx.paths.gitDir, boardRef: w.ref, canonicalRoot: null };
    const gitT = await roomTimeline(new GitRoomSource(roomSpec, createVizGit({ runner, gitDir: fx.paths.gitDir, dataDir }), { fs: realFs, clock: realClock }));
    return { git: gitT, demo, demoBytes };
  } finally {
    await fx.cleanup();
  }
}

