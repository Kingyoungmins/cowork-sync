// Plan 8a Task 16: `npm run viz:golden [-- --update]` (F-8a-5, X-91) — the one way every plan regenerates 8a's goldens — and
// T-VIZ-golden-board (12 §7 in its board form, R-V37; INV-VIZ-DET, VIZ-27). The fast tests run tools/viz/golden.ts's runGolden
// in-process over a temp copy of Task 6's row fixtures and goldens (no board is built), and its CLI entry once as a subprocess;
// the board test is a slow suite (COWORK_VIZ_SLOW=1, viz-slow.yml).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, unlinkSync, utimesSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GOLDEN_BOARDS, goldenBoardTimelines, ROW_GOLDENS, runGolden, type GoldenFile, type GoldenIo, type GoldenSet } from '../../../tools/viz/golden.js';
import { makeTempRoot } from '../../helpers/tmp.js';
import { ROW_FIXTURE_DIR, ROW_GOLDEN_DIR } from '../../helpers/vizRows.js';

const REPO = fileURLToPath(new URL('../../../', import.meta.url));
const GOLDEN_TOOL = path.join(REPO, 'tools', 'viz', 'golden.ts');
const abs = (root: string, rel: string): string => path.join(root, ...rel.split('/'));

/** The output lines of a run. */
function sink(): GoldenIo & { lines: string[]; errors: string[] } {
  const lines: string[] = [];
  const errors: string[] = [];
  return { lines, errors, out: (l) => lines.push(l), err: (l) => errors.push(l) };
}

/** The row set, generated once per test (the fixtures do not change within a test; board_full alone takes seconds). */
function rowsOnce(): GoldenSet {
  let files: Promise<GoldenFile[]> | null = null;
  return { name: ROW_GOLDENS.name, files: (root) => (files ??= ROW_GOLDENS.files(root)) };
}

/** A temp root holding a copy of the row fixtures and their goldens, at the repository's relative paths. */
function copyRows(root: string): string[] {
  const names: string[] = [];
  for (const dir of [ROW_FIXTURE_DIR, ROW_GOLDEN_DIR]) {
    mkdirSync(abs(root, dir), { recursive: true });
    for (const n of readdirSync(abs(REPO, dir)).sort()) {
      copyFileSync(abs(REPO, `${dir}/${n}`), abs(root, `${dir}/${n}`));
      if (dir === ROW_GOLDEN_DIR) names.push(`${dir}/${n}`);
    }
  }
  return names;
}

test('viz:golden --update regenerates the row goldens of Task 6 byte for byte, and compare mode reports the first differing file', async () => {
  const { root, cleanup } = await makeTempRoot('viz-golden-rows');
  try {
    const goldens = copyRows(root);
    const rows = rowsOnce();
    assert.ok(goldens.length >= 40, `${goldens.length} row goldens`);
    const ok = sink();
    assert.equal(await runGolden([], { root, sets: [rows], io: ok }), 0, ok.errors.join('\n'));
    assert.deepEqual(ok.lines, [`viz:golden: ${goldens.length} golden files match`]);

    // Two goldens go stale: one is deleted, one gains a byte. Compare mode names the first in path order and writes nothing.
    const missing = `${ROW_GOLDEN_DIR}/genesis.events.json`;
    const changed = `${ROW_GOLDEN_DIR}/save.events.json`;
    unlinkSync(abs(root, missing));
    const stale = Buffer.concat([readFileSync(abs(root, changed)), Buffer.from('x', 'utf8')]);
    writeFileSync(abs(root, changed), stale);
    const cmp = sink();
    assert.equal(await runGolden([], { root, sets: [rows], io: cmp }), 1);
    assert.deepEqual(cmp.errors, [
      `viz:golden: ${missing} is missing (2 of ${goldens.length} golden files differ)`,
      'viz:golden: run `npm run viz:golden -- --update` and review the diff',
    ]);
    assert.equal(existsSync(abs(root, missing)), false, 'compare mode creates nothing');
    assert.ok(readFileSync(abs(root, changed)).equals(stale), 'compare mode rewrites nothing');

    // With only the second one stale, it is the first differing file, reported with the first line that differs.
    copyFileSync(abs(REPO, missing), abs(root, missing));
    const cmp2 = sink();
    assert.equal(await runGolden([], { root, sets: [rows], io: cmp2 }), 1);
    const lastLine = readFileSync(abs(REPO, changed), 'utf8').split('\n').length;
    assert.equal(cmp2.errors[0], `viz:golden: ${changed} differs at line ${lastLine} (1 of ${goldens.length} golden files differ)`);
    unlinkSync(abs(root, missing));

    // --update writes exactly the two, byte for byte equal to the repository's goldens (LF, no BOM).
    const up = sink();
    assert.equal(await runGolden(['--update'], { root, sets: [rows], io: up }), 0, up.errors.join('\n'));
    assert.deepEqual(up.lines, [`viz:golden: wrote ${missing}`, `viz:golden: wrote ${changed}`, `viz:golden: 2 written, ${goldens.length - 2} unchanged`]);
    for (const g of goldens) {
      const bytes = readFileSync(abs(root, g));
      assert.ok(bytes.equals(readFileSync(abs(REPO, g))), `${g} regenerated byte for byte`);
      assert.ok(!bytes.includes(0x0d) && !(bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf), `${g}: LF, no BOM`);
    }
    const again = sink();
    assert.equal(await runGolden([], { root, sets: [rows], io: again }), 0);
  } finally {
    await cleanup();
  }
});

test('viz:golden compares without --update and rewrites only with --update', async () => {
  const { root, cleanup } = await makeTempRoot('viz-golden-modes');
  try {
    const goldens = copyRows(root);
    const rows = rowsOnce();
    // An old mtime on every golden: --update must leave the files it does not rewrite untouched.
    const old = new Date('2001-02-03T04:05:06Z');
    for (const g of goldens) utimesSync(abs(root, g), old, old);
    const target = `${ROW_GOLDEN_DIR}/freeze.events.json`;
    writeFileSync(abs(root, target), Buffer.from('{}\n', 'utf8'));
    utimesSync(abs(root, target), old, old);

    // Compare mode (no flag), twice: exit 1 each time, the stale file and every mtime unchanged.
    for (let i = 0; i < 2; i++) {
      const cmp = sink();
      assert.equal(await runGolden([], { root, sets: [rows], io: cmp }), 1);
      assert.match(cmp.errors[0]!, /freeze\.events\.json differs at line 1 \(1 of \d+ golden files differ\)$/);
      assert.equal(readFileSync(abs(root, target), 'utf8'), '{}\n');
      for (const g of goldens) assert.equal(statSync(abs(root, g)).mtimeMs, old.getTime(), g);
    }
    // An unknown argument is a usage error: exit 2, nothing compared or written.
    const bad = sink();
    assert.equal(await runGolden(['--updat'], { root, sets: [rows], io: bad }), 2);
    assert.deepEqual(bad.errors, ['usage: npm run viz:golden [-- --update]']);
    assert.equal(readFileSync(abs(root, target), 'utf8'), '{}\n');

    // --update rewrites only the stale file.
    const up = sink();
    assert.equal(await runGolden(['--update'], { root, sets: [rows], io: up }), 0);
    assert.deepEqual(up.lines, [`viz:golden: wrote ${target}`, `viz:golden: 1 written, ${goldens.length - 1} unchanged`]);
    assert.ok(readFileSync(abs(root, target)).equals(readFileSync(abs(REPO, target))));
    for (const g of goldens) if (g !== target) assert.equal(statSync(abs(root, g)).mtimeMs, old.getTime(), `${g} not rewritten`);

    // The CLI entry runs (as `npm run viz:golden` starts it): a usage error exits 2 before any golden is built.
    const r = spawnSync(process.execPath, ['--import', 'tsx', GOLDEN_TOOL, '--bogus'], { cwd: REPO, encoding: 'utf8' });
    assert.equal(r.status, 2, r.stderr);
    assert.equal(r.stderr, 'usage: npm run viz:golden [-- --update]\n');
    // package.json: the one script line, directly after "build" (R-V02).
    const scripts = Object.entries((JSON.parse(readFileSync(abs(REPO, 'package.json'), 'utf8')) as { scripts: Record<string, string> }).scripts);
    const at = scripts.findIndex(([k]) => k === 'build');
    assert.deepEqual(scripts[at + 1], ['viz:golden', 'tsx tools/viz/golden.ts']);
  } finally {
    await cleanup();
  }
});

// ---- T-VIZ-golden-board (R-V37; COWORK_VIZ_SLOW=1, viz-slow.yml) -------------------------------------------------------------

const SLOW = process.env['COWORK_VIZ_SLOW'] === '1';

/** The rows a serialized timeline shows: each event's kind, kind:detail (badge, level, sign, conflict, bang), the badge's on, sub 1,001/1,002 forms, big-table and paper-plane publishes. */
function rowsOf(text: string): Set<string> {
  const rows = new Set<string>();
  const t = JSON.parse(text) as { events: Array<Record<string, unknown>> };
  for (const e of t.events) {
    const kind = String(e['kind']);
    const detail = e['badge'] ?? e['level'] ?? e['sign'] ?? e['conflict'] ?? e['bang'];
    rows.add(kind);
    if (typeof detail === 'string') rows.add(`${kind}:${detail}`);
    if (kind === 'person_badge') rows.add(`${kind}:${String(detail)}:${String(e['on'])}`).add(`${kind}:${String(detail)}@${String(e['sub'])}`);
    if (e['sub'] === 1001 || e['sub'] === 1002) rows.add(`${kind}@${String(e['sub'])}`);
    if (kind === 'publish' && Array.isArray(e['paths']) && e['paths'].length === 0 && Number(e['n']) > 256) rows.add('publish:big_table');
    if (kind === 'publish' && Array.isArray(e['others']) && e['others'].length > 0) rows.add('publish:paper_planes');
  }
  // A same-epoch rejoin: a person_enter after that peer's person_exit.
  const exits = new Map<string, number>();
  for (const e of t.events) {
    if (e['kind'] === 'person_exit') exits.set(String(e['peer']), Number(e['height']));
    if (e['kind'] === 'person_enter' && (exits.get(String(e['peer'])) ?? Infinity) < Number(e['height'])) rows.add('person_enter:rejoin');
  }
  return rows;
}

/** Every Plan 2 row of 12 §3.4 (T-VIZ-timeline-fixtures' plan2Rows) as rowsOf names it; board 3 adds record_count's near_full. */
const PLAN2_ROWS = [
  'room_open', 'person_enter', 'person_enter:rejoin', 'person_respawn', 'person_exit', 'pet_spawn', 'pet_spawn@1001', 'pet_poof', 'publish',
  'publish:big_table', 'publish:paper_planes', 'room_sign:branch_moved', 'save', 'person_freeze', 'person_thaw', 'person_slowed', 'person_bang:host',
  'person_badge:version:true', 'person_badge:rules:true', 'person_badge:rules:false', 'person_badge:rules@1002', 'person_badge:credit:true',
  'person_badge:health:true', 'conflict:breach', 'conflict:generic', 'room_badge:full', 'room_badge:none', 'person_ghost', 'person_unghost', 'pose_relaxed',
];

test('T-VIZ-golden-board: for three scripted boards (three peers, ≥ 300 heights, every row the Plan 2 fold applies, one > 256-path change-set, a respawn, a freeze, a throttle, a leave and same-epoch rejoin, a not_commit live commit, a three-parent live commit and a malformed board commit) the git-source timeline and the exported demo\'s timeline are byte-identical on every OS; a second run is byte-identical; on the Linux leg both equal test/golden/viz/board-<n>.timeline.json', { skip: SLOW ? false : 'slow suite: set COWORK_VIZ_SLOW=1 (viz-slow.yml)' }, async (t) => {
  for (const { n } of GOLDEN_BOARDS) {
    const first = await goldenBoardTimelines(n);
    assert.equal(first.demo.text, first.git.text, `board ${n}: the git source's and the exported demo's timelines, byte for byte`);
    assert.ok(first.git.heights >= 300, `board ${n}: ${first.git.heights} heights`);
    // R-V19: one malformed board commit and three changed frames without a live step (not_commit, the commit after it, three
    // parents); only their unknown counts differ between the two timelines.
    assert.deepEqual([first.git.malformed, first.git.shapeNull, first.git.unknown - first.demo.unknown], [1, 3, 4], `board ${n}: R-V19 frames`);
    const rows = rowsOf(first.git.text);
    for (const r of [...PLAN2_ROWS, ...(n === 3 ? ['room_badge:near_full'] : [])]) assert.ok(rows.has(r), `board ${n} shows ${r}`);
    const peers = new Set((JSON.parse(first.git.text) as { layout: { homeOrder: string[] } }).layout.homeOrder);
    assert.equal(peers.size, 3, `board ${n}: three peers`);

    const second = await goldenBoardTimelines(n);
    assert.equal(second.git.text, first.git.text, `board ${n}: a second run, git source`);
    assert.equal(second.demo.text, first.demo.text, `board ${n}: a second run, demo`);
    assert.ok(second.demoBytes.equals(first.demoBytes), `board ${n}: a second run exports the same demo log`);

    const golden = readFileSync(abs(REPO, `test/golden/viz/board-${n}.timeline.json`));
    assert.ok(!golden.includes(0x0d) && !(golden[0] === 0xef && golden[1] === 0xbb && golden[2] === 0xbf), `board ${n}: the golden is LF without BOM`);
    const same = golden.equals(Buffer.from(`${first.git.text}\n`, 'utf8'));
    if (process.platform === 'linux') assert.ok(same, `board ${n}: equals test/golden/viz/board-${n}.timeline.json (npm run viz:golden -- --update, then review the diff)`);
    else t.diagnostic(`board ${n}: the golden is compared on the Linux leg (here it is ${same ? 'equal' : 'different'})`);
  }
});
